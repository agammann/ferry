import assert from 'node:assert/strict';
import { auditOccurrences } from '../occurrences.mjs';
import { compare } from '../ferry.mjs';
import { mkdtempSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
const event=(uid,count,summary)=>`BEGIN:VEVENT\nUID:${uid}\nDTSTART:20270101T000000Z\nRRULE:FREQ=DAILY;COUNT=${count}\nSUMMARY:${summary}\nEND:VEVENT\n`;
const cal=(events)=>`BEGIN:VCALENDAR\n${events}END:VCALENDAR\n`;
const audit=(a,b=a)=>auditOccurrences(a,b,'2027-01-01','2029-01-01');
const one=cal(event('a',1,'ordinary'));
assert.equal(audit(one).findings[0].status,'preserved');
assert.equal(audit(one,cal(event('a',1,'changed'))).findings[0].status,'changed');
assert.equal(audit(cal(event('a',4,'ordinary'))).findings[0].before.length,4);
assert.throws(()=>audit(cal(event('a',500,'x'.repeat(4096)))),/Occurrence output budget exceeded/);
assert.throws(()=>audit(cal(event('a',300,'\\'.repeat(1024)))),/Occurrence output budget exceeded/);
const many=cal(Array.from({length:30},(_,i)=>event(`id${i}`,5,'x'.repeat(4000))).join(''));
assert.throws(()=>audit(many),/Occurrence output budget exceeded/);
const orphan=`BEGIN:VEVENT\nUID:bad\nRECURRENCE-ID:20300101T000000Z\nDTSTART:20300101T000000Z\nEND:VEVENT\n`;
const mixed=cal(event('bad',50,'x'.repeat(4000))+orphan+event('good',100,'x'.repeat(4000)));
assert.deepEqual(audit(mixed).findings.map(x=>x.status),['unverifiable','preserved']);
const huge=cal(event('a',1,'x'.repeat(1024*1024)));
assert.throws(()=>audit(huge),/Calendar input budget exceeded/);
assert.throws(()=>compare(huge,one),/Calendar input budget exceeded/);
const dir=mkdtempSync(join(tmpdir(),'ferry-synthetic-'));
try {
 const file=join(dir,'input.ics'), report=join(dir,'report.json');
 writeFileSync(file,cal(event('a',500,'x'.repeat(4096))));
 const run=spawnSync(process.execPath,['ferry.mjs',file,file,report,'2027-01-01','2029-01-01'],{encoding:'utf8'});
 assert.equal(run.status,1); assert.match(run.stderr,/Occurrence output budget exceeded/);
 assert.equal(existsSync(report),false); assert.equal(existsSync(report+'.html'),false);
 writeFileSync(file,huge);
 const oversized=spawnSync(process.execPath,['ferry.mjs',file,file,report,'2027-01-01','2029-01-01'],{encoding:'utf8'});
 assert.equal(oversized.status,1); assert.match(oversized.stderr,/Calendar input budget exceeded/); assert.equal(existsSync(report),false);
 writeFileSync(file,one);
 const ok=spawnSync(process.execPath,['ferry.mjs',file,file,report,'2027-01-01','2029-01-01'],{encoding:'utf8'});
 assert.equal(ok.status,0); assert.equal(existsSync(report),true); assert.equal(existsSync(report+'.html'),true);
} finally { rmSync(dir,{recursive:true,force:true}); }
console.log('synthetic candidate checks passed');
